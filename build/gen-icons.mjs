// US-009 AC-5, AC-7 (ticket #28): makes `src/core/scheme/icons.ts` from the list of the
// font's icon names and code points (`assets/fonts/RPGAwesome-icons.txt`, read on
// 2026-11-13 from the font's own CSS, `rpg-awesome.css` of RPG Awesome 0.0.2: one line
// `<name> <hex code point>` per name). Run `node build/gen-icons.mjs` after the list
// changes; a tooling test compares the committed file with this function's output.
/* global console, process */
import {readFileSync, writeFileSync} from 'node:fs';
import {join} from 'node:path';
import {format, resolveConfig} from 'prettier';

const HEAD = [
  '// GENERATED by build/gen-icons.mjs from assets/fonts/RPGAwesome-icons.txt; do not edit.',
  '// US-009 AC-5, AC-7: the icon names of the bundled font (RPG Awesome) and their code',
  '// points. A name that is not here is never written into the Typst source.',
  'const TABLE: Readonly<Record<string, number>> = Object.freeze({',
];
const TAIL = [
  '});',
  '',
  "/** US-009 AC-5: every icon name, in the order of the font's list. */",
  'export const ICON_NAMES: readonly string[] = Object.freeze(Object.keys(TABLE));',
  '',
  '/**',
  ' * US-009 AC-5, AC-7: the code point of icon `name` in the bundled font, or',
  ' * `undefined` for a name that is not one (an empty name, a word that is an',
  ' * object key such as `constructor`). Names compare without case and surrounding',
  ' * spaces.',
  ' */',
  'export function iconCodePoint(name: string): number | undefined {',
  '  const key = name.trim().toLowerCase();',
  '  return Object.prototype.hasOwnProperty.call(TABLE, key)',
  '    ? TABLE[key]',
  '    : undefined;',
  '}',
  '',
];

/**
 * US-009 AC-5: `iconsSource(listText)` formatted with the project's Prettier
 * settings, which is the text of the committed `icons.ts` (so a check can compare
 * file and function byte for byte).
 */
export async function iconsFile(
  listText,
  root = join(import.meta.dirname, '..'),
) {
  const options =
    (await resolveConfig(join(root, 'src/core/scheme/icons.ts'))) ?? {};
  return format(iconsSource(listText), {...options, parser: 'typescript'});
}

/**
 * US-009 AC-5: the text of `icons.ts` for `listText` (lines `<name> <hex>`).
 * Pure and deterministic: the names stay in the order of the list. Refuses a line
 * that is not `<name> <hex>`, a name written twice and a code point outside the
 * private-use range of the font (U+E900 to U+EBFF).
 */
export function iconsSource(listText) {
  const rows = [];
  const seen = new Set();
  for (const line of listText.split('\n')) {
    if (line.trim() === '') continue;
    const m = /^([a-z0-9-]+) ([0-9a-f]{4})$/.exec(line.trim());
    if (m === null)
      throw new Error('Not an icon line: ' + JSON.stringify(line));
    const code = Number.parseInt(m[2], 16);
    if (code < 0xe900 || code > 0xebff)
      throw new Error('Code point of ' + m[1] + ' is outside U+E900 to U+EBFF');
    if (seen.has(m[1])) throw new Error('Name written twice: ' + m[1]);
    seen.add(m[1]);
    rows.push("  '" + m[1] + "': 0x" + m[2] + ',');
  }
  return [...HEAD, ...rows, ...TAIL].join('\n');
}

if (import.meta.url === 'file://' + process.argv[1]) {
  const root = join(import.meta.dirname, '..');
  const list = readFileSync(
    join(root, 'assets/fonts/RPGAwesome-icons.txt'),
    'utf8',
  );
  writeFileSync(
    join(root, 'src/core/scheme/icons.ts'),
    await iconsFile(list, root),
  );
  console.log('Wrote src/core/scheme/icons.ts');
}
